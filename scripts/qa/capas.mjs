// Capturas de las capas en celular: menú, elección de línea, visor y filtro activo.
import { chromium } from 'playwright-core';
const URL = process.argv[2] || 'http://localhost:5641/';
const OUT = '.cache/qa/capturas';
const nav = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
const ctx = await nav.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true, reducedMotion: 'no-preference' });
await ctx.addInitScript(() => sessionStorage.setItem('hp-intro', '1'));
const page = await ctx.newPage();
await page.goto(URL);
await page.waitForTimeout(1200);
await page.click('[data-abrir-menu]');
await page.waitForTimeout(900);
await page.screenshot({ path: `${OUT}/capa-menu.png` });
await page.keyboard.press('Escape');
await page.waitForTimeout(600);
await page.evaluate(() => document.querySelector('#p-sala-charleston').scrollIntoView({ block: 'center' }));
await page.waitForTimeout(900);
await page.screenshot({ path: `${OUT}/capa-carta.png` });
await page.click('#p-sala-charleston [data-consulta]');
await page.waitForTimeout(800);
await page.screenshot({ path: `${OUT}/capa-lineas.png` });
await page.keyboard.press('Escape');
await page.waitForTimeout(500);
await page.evaluate(() => document.querySelector('#p-sala-audi').scrollIntoView({ block: 'center' }));
await page.waitForTimeout(700);
await page.click('#p-sala-audi [data-visor]');
await page.waitForTimeout(1200);
await page.screenshot({ path: `${OUT}/capa-visor.png` });
await page.keyboard.press('Escape');
await page.waitForTimeout(500);
await page.click('[data-filtro="en-l"]');
await page.waitForTimeout(1200);
await page.screenshot({ path: `${OUT}/capa-filtro.png` });
await nav.close();
console.log('ok');
